#!/usr/bin/env python3
import os, re, shutil, subprocess, sys

def findObjdump():
    for name in ("x86_64-w64-mingw32-objdump", "objdump"):
        if shutil.which(name):
            return name
    sys.exit("objdump not found")

def parseExports(dll):
    out = subprocess.run([findObjdump(), "-p", dll], capture_output=True, text=True, check=True).stdout
    if "[Ordinal/Name Pointer] Table" not in out:
        sys.exit("no export table in " + dll)
    ordinals = {int(m.group(1)) for m in re.finditer(r"\+base\[\s*(\d+)\]\s+[0-9a-fA-F]+ (?:Export|Forwarder) RVA", out)}
    names = {}
    section = out[out.index("[Ordinal/Name Pointer] Table"):]
    for m in re.finditer(r"^\s+\[\s*(\d+)\]\s+(\S+)\s*$", section, re.M):
        names[int(m.group(1))] = m.group(2)
    return sorted(ordinals | set(names)), names

def main():
    if len(sys.argv) < 2:
        sys.exit("usage: genProxy.py <real.dll> [outDir]")
    dll = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    outDir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "loader", "proxy")
    os.makedirs(outDir, exist_ok=True)
    stem = os.path.splitext(os.path.basename(dll))[0].lower()
    ordinals, names = parseExports(dll)

    with open(os.path.join(outDir, stem + ".def"), "w") as f:
        f.write(f"LIBRARY {stem}\nEXPORTS\n")
        for o in ordinals:
            f.write(f"    {names[o]} @{o}\n" if o in names else f"    wheatOrd{o} @{o} NONAME\n")

    with open(os.path.join(outDir, stem + "Exports.inc"), "w") as f:
        f.write(f"// generated by tools/genProxy.py from {os.path.basename(dll)}\n")
        f.write(f'#define WHEAT_PROXY_DLL_NAME L"{stem}.dll"\n#define WHEAT_PROXY_COUNT {len(ordinals)}\n\n')
        f.write("struct ProxyExport { const char* name; unsigned ordinal; };\n")
        f.write("static const ProxyExport kProxyExports[WHEAT_PROXY_COUNT] = {\n")
        for o in ordinals:
            f.write(f'    {{"{names[o]}", {o}}},\n' if o in names else f"    {{nullptr, {o}}},\n")
        f.write("};\n\n")
        for i, o in enumerate(ordinals):
            label = names.get(o, f"wheatOrd{o}")
            f.write(f'asm(".text\\n.p2align 4\\n.globl {label}\\n{label}:\\n\\tjmp *gReal+{i}*8(%rip)\\n");\n')
    print(f"{stem}: {len(ordinals)} exports ({len(names)} named, {len(ordinals) - len(names)} by ordinal only)")

main()
